"""
Sync Amazon US Settlement Reports into Amazon US Settlement doctype.

Source: GET_V2_SETTLEMENT_REPORT_DATA_FLAT_FILE_V2 (SP-API Reports API).
  - Auto-generated by Amazon every ~2 weeks when a billing period closes.
  - Cannot be requested on demand — only retrieved after generation.
  - V2 format: tab-delimited flat file, all amounts in three columns:
      amount-type, amount-description, amount
  - Deprecated formats (XML, flat-file v1) removed November 11, 2026.

Flow:
  1. list_reports() — fetch recently DONE settlement reports from SP-API
  2. Skip any settlement-id already stored in DB (idempotent)
  3. For new reports: download_report() → parse TSV
  4. Extract header (settlement-id, dates, total)
  5. Parse transaction lines → Amazon US Settlement Line rows
  6. Compute summary amounts (gross_revenue, fees, refunds, reimbursements)
  7. Insert Amazon US Settlement doc with all lines

Reconciliation:
  - Join Settlement Line.order_id → Amazon US Order to cross-check amounts
  - Settlement `amount-type=Principal` net sum ≈ AR Invoice item total
  - Fees/reimbursements → separate SAP B1 journal entry (Phase C post-go-live)

Scheduler: daily at 07:00 UTC via hooks.py.
Manual trigger: api/ops.py enqueue_settlement_sync.
"""
import csv
import io
import json
from datetime import datetime, timezone

import frappe
from frappe.utils import now_datetime

from khanal_tech_integrations.amazon_us.client.reports import (
    download_report,
    list_reports,
)

_REPORT_TYPE = "GET_V2_SETTLEMENT_REPORT_DATA_FLAT_FILE_V2"
_SETTLEMENT_DOCTYPE = "Amazon US Settlement"
_LINE_DOCTYPE = "Amazon US Settlement Line"
_SETTINGS_DOCTYPE = "Amazon US Settings"

# V2 format: amount-type is the category, amount-description is the line item.
# ItemFees = Commission + FBA fees (negative). ItemPrice = revenue components.
_FEE_AMOUNT_TYPES = {"ItemFees", "OtherFees"}
_REIMBURSEMENT_TX_TYPES = {"FBAInventoryReimbursement", "Adjustment", "REVERSAL_REIMBURSEMENT"}


# ─── Cache helpers ────────────────────────────────────────────────────────────

def _cache_key(job_id):
    return f"amz_us_settlement_{job_id}"


def _emit(job_id, msg, level="info"):
    if not job_id:
        frappe.logger().info(f"[settlement] {msg}")
        return
    raw = frappe.cache().get_value(_cache_key(job_id)) or "{}"
    try:
        data = json.loads(raw)
    except Exception:
        data = {}
    log = data.get("log", [])
    log.append({"msg": msg, "level": level, "at": str(now_datetime())})
    data["log"] = log[-100:]
    frappe.cache().set_value(_cache_key(job_id), json.dumps(data), expires_in_sec=3600)


def _set(job_id, updates):
    if not job_id:
        return
    raw = frappe.cache().get_value(_cache_key(job_id)) or "{}"
    try:
        data = json.loads(raw)
    except Exception:
        data = {}
    data.update(updates)
    frappe.cache().set_value(_cache_key(job_id), json.dumps(data), expires_in_sec=3600)


# ─── Parsing ──────────────────────────────────────────────────────────────────

def _parse_utc_dt(raw):
    """Convert UTC datetime string from settlement report to Frappe datetime string.
    Handles both ISO 8601 ("2026-05-29T12:31:48Z") and V2 flat-file format
    ("2026-05-29 12:31:48 UTC").
    """
    if not raw:
        return None
    s = str(raw).strip()
    try:
        # V2 flat-file format: "2026-05-29 12:31:48 UTC"
        if s.endswith(" UTC"):
            s = s[:-4].replace(" ", "T") + "+00:00"
        elif s.endswith("Z"):
            s = s[:-1] + "+00:00"
        dt = datetime.fromisoformat(s)
        return dt.strftime("%Y-%m-%d %H:%M:%S")
    except Exception:
        return None


def _parse_date(raw):
    """Return YYYY-MM-DD from a UTC ISO 8601 string."""
    dt_str = _parse_utc_dt(raw)
    return dt_str[:10] if dt_str else None


def _parse_amount(raw):
    """Safe float parse for settlement amounts (can be negative)."""
    try:
        return float(str(raw).strip() or "0")
    except Exception:
        return 0.0


def _parse_settlement_report(content):
    """
    Parse a V2 settlement flat-file (tab-delimited).

    Actual format (24 columns, single flat table):
      Row 0 : ALL column headers (settlement + tx columns in one row)
      Row 1 : Settlement summary row — settlement-id/dates/total/currency filled, tx cols empty
      Row 2+: Transaction rows — tx cols filled, settlement cols mostly empty

    header_dict = zip(row0, row1) → settlement-id, dates, total, currency etc.
    tx_lines    = DictReader over entire file (row0=headers, row1=summary, row2+=tx rows)
                  — caller must skip rows where transaction-type is empty.

    Returns (header_dict, [line_dicts]).
    """
    lines = content.splitlines()
    if not lines:
        raise ValueError("Empty settlement report content")

    # Row 0: settlement-level metadata
    header_cols = [c.strip() for c in lines[0].split("\t")]
    header_vals = [c.strip() for c in (lines[1].split("\t") if len(lines) > 1 else [])]
    header = dict(zip(header_cols, header_vals))

    # Find the transaction section — look for the line containing "transaction-type"
    tx_start = None
    for i, line in enumerate(lines):
        if "transaction-type" in line.lower():
            tx_start = i
            break

    if tx_start is None:
        return header, []

    # Parse tab-delimited transaction lines
    tx_content = "\n".join(lines[tx_start:])
    reader = csv.DictReader(io.StringIO(tx_content), delimiter="\t")
    tx_lines = list(reader)

    return header, tx_lines


def _compute_summary(tx_lines):
    """
    Compute gross_revenue, total_fees, total_refunds, total_reimbursements.

    V2 flat-file columns:
      transaction-type: Order | Refund | Transfer | ServiceFee | FBAInventoryReimbursement | ...
      amount-type:      ItemPrice | ItemFees | ItemWithheldTax | Promotion | OtherFees | ...
      amount-description: Principal | Tax | Commission | FBAPerUnitFulfillmentFee | ...

    gross_revenue  = Order rows where amount-type=ItemPrice, amount-description=Principal
    total_fees     = all rows where amount-type in ItemFees/OtherFees, or tx-type=ServiceFee
    total_refunds  = all Refund tx rows
    total_reimb    = FBAInventoryReimbursement / Adjustment tx rows
    """
    gross_revenue = total_fees = total_refunds = total_reimbursements = 0.0

    for row in tx_lines:
        tx_type = (row.get("transaction-type") or "").strip()
        if not tx_type:
            continue  # settlement summary row — no tx data
        amt_type = (row.get("amount-type") or "").strip()
        amt_desc = (row.get("amount-description") or "").strip()
        amount = _parse_amount(row.get("amount") or "0")

        if tx_type == "Refund":
            total_refunds += amount
        elif tx_type in _REIMBURSEMENT_TX_TYPES:
            total_reimbursements += amount
        elif amt_type in _FEE_AMOUNT_TYPES or tx_type == "ServiceFee":
            total_fees += amount
        elif amt_type == "ItemPrice" and amt_desc == "Principal":
            gross_revenue += amount

    return {
        "gross_revenue": round(gross_revenue, 2),
        "total_fees": round(total_fees, 2),
        "total_refunds": round(total_refunds, 2),
        "total_reimbursements": round(total_reimbursements, 2),
    }


# ─── Core sync ────────────────────────────────────────────────────────────────

def _build_doc_from_content(doc_id, content, skip_if_exists=True, job_id=None):
    """
    Parse settlement report content and insert/replace the Settlement doc.
    Returns settlement_id, or None if skipped (already exists and skip_if_exists=True).
    """
    header, tx_lines = _parse_settlement_report(content)

    settlement_id = str(header.get("settlement-id", "")).strip()
    if not settlement_id:
        _emit(job_id, "Could not parse settlement-id from report — skipping", "warn")
        return None

    if skip_if_exists and frappe.db.exists(_SETTLEMENT_DOCTYPE, settlement_id):
        _emit(job_id, f"Settlement {settlement_id} already in DB — skipping")
        return None

    summary = _compute_summary(tx_lines)

    line_rows = []
    for row in tx_lines:
        tx_type = (row.get("transaction-type") or "").strip()
        if not tx_type:
            continue  # skip the settlement summary row (no tx data)
        line_rows.append({
            "doctype": _LINE_DOCTYPE,
            "transaction_type": tx_type[:140],
            "order_id": (row.get("order-id") or "")[:50],
            "shipment_id": (row.get("shipment-id") or "")[:50],
            "posted_date": _parse_date(row.get("posted-date")),
            "amount_type": (row.get("amount-type") or "")[:140],
            "amount_description": (row.get("amount-description") or "")[:140],
            "amount": _parse_amount(row.get("amount") or "0"),
            "sku": (row.get("sku") or "")[:140],
            "quantity_purchased": int(float(row.get("quantity-purchased") or 0)),
            "adjustment_id": (row.get("adjustment-id") or "")[:50],
            "promotion_id": (row.get("promotion-id") or "")[:50],
            "marketplace_name": (row.get("marketplace-name") or "")[:140],
        })

    try:
        if frappe.db.exists(_SETTLEMENT_DOCTYPE, settlement_id):
            frappe.delete_doc(_SETTLEMENT_DOCTYPE, settlement_id, ignore_permissions=True)
        doc = frappe.get_doc({
            "doctype": _SETTLEMENT_DOCTYPE,
            "settlement_id": settlement_id,
            "status": "processed",
            "settlement_start_date": _parse_utc_dt(header.get("settlement-start-date")),
            "settlement_end_date": _parse_utc_dt(header.get("settlement-end-date")),
            "deposit_date": _parse_utc_dt(header.get("deposit-date")),
            "total_amount": _parse_amount(header.get("total-amount") or "0"),
            "currency": (header.get("currency") or "USD")[:10],
            "report_document_id": doc_id,
            "processed_at": str(now_datetime()),
            "lines": line_rows,
            **summary,
        })
        doc.insert(ignore_permissions=True)
        frappe.db.commit()
    except Exception:
        frappe.db.rollback()
        raise

    _emit(
        job_id,
        f"Stored settlement {settlement_id}: "
        f"total={header.get('total-amount')} currency={header.get('currency')} "
        f"lines={len(line_rows)} revenue={summary['gross_revenue']} fees={summary['total_fees']}",
    )
    return settlement_id


def _process_one_report(report_meta, job_id=None):
    """
    Download and store one settlement report. Returns settlement_id or None if skipped.
    report_meta: dict from list_reports() — has reportDocumentId, dataStartTime, etc.
    """
    doc_id = report_meta.get("reportDocumentId")
    if not doc_id:
        _emit(job_id, "Report has no reportDocumentId — skipping", "warn")
        return None

    content = download_report(doc_id)
    return _build_doc_from_content(doc_id, content, skip_if_exists=True, job_id=job_id)


def reprocess_settlement(settlement_id, job_id=None):
    """
    Re-download and re-parse an existing settlement (fixes corrupt/zero-amount records).
    Deletes the stored doc and rebuilds from SP-API.
    """
    doc_id = frappe.db.get_value(_SETTLEMENT_DOCTYPE, settlement_id, "report_document_id")
    if not doc_id:
        raise ValueError(f"Settlement {settlement_id} not found or has no report_document_id")
    _emit(job_id, f"Reprocessing settlement {settlement_id} from doc {doc_id}...")
    content = download_report(doc_id)
    return _build_doc_from_content(doc_id, content, skip_if_exists=False, job_id=job_id)


def reprocess_all_settlements(progress_id=None):
    """
    Reprocess all stored settlements from SP-API (use after parser fix).
    Returns summary dict.
    """
    _set(progress_id, {"status": "running"})
    _emit(progress_id, "Reprocessing all stored settlements...")

    all_ids = frappe.get_all(
        _SETTLEMENT_DOCTYPE,
        fields=["settlement_id", "report_document_id"],
        order_by="deposit_date asc",
    )
    _emit(progress_id, f"Found {len(all_ids)} stored settlements to reprocess")

    success = error = 0
    for rec in all_ids:
        sid = rec.settlement_id
        doc_id = rec.report_document_id
        if not doc_id:
            _emit(progress_id, f"Settlement {sid} has no report_document_id — skipping", "warn")
            error += 1
            continue
        try:
            _emit(progress_id, f"Reprocessing {sid}...")
            content = download_report(doc_id)
            _build_doc_from_content(doc_id, content, skip_if_exists=False, job_id=progress_id)
            success += 1
        except Exception as e:
            _emit(progress_id, f"Error reprocessing {sid}: {e}", "error")
            frappe.log_error(str(e), f"Amazon US Settlement reprocess {sid}")
            error += 1

    result = {"status": "done", "success": success, "errors": error}
    _set(progress_id, result)
    return result


def sync_settlement_reports(progress_id=None):
    """
    Fetch list of completed settlement reports from SP-API and store new ones.
    Idempotent — skips settlement_ids already in DB.
    Returns summary dict.
    """
    _set(progress_id, {"status": "running"})
    _emit(progress_id, "Checking for new settlement reports...")

    marketplace_id = frappe.db.get_single_value(_SETTINGS_DOCTYPE, "marketplace_id") or None
    try:
        reports = list_reports(
            _REPORT_TYPE,
            marketplace_id=marketplace_id,
            processing_status="DONE",
            page_size=10,
        )
    except Exception as e:
        err = str(e)
        _emit(progress_id, f"list_reports failed: {err}", "error")
        _set(progress_id, {"status": "error", "message": err})
        frappe.log_error(err, "Amazon US Settlement — list_reports")
        return {"status": "error", "message": err}

    _emit(progress_id, f"Found {len(reports)} completed settlement reports from SP-API")

    new_count = skipped_count = error_count = 0
    new_ids = []

    for report_meta in reports:
        try:
            sid = _process_one_report(report_meta, progress_id)
            if sid:
                new_count += 1
                new_ids.append(sid)
            else:
                skipped_count += 1
        except Exception as e:
            err = str(e)
            _emit(progress_id, f"Error processing report {report_meta.get('reportId')}: {err}", "error")
            frappe.log_error(err, "Amazon US Settlement — process report")
            error_count += 1

    result = {
        "status": "done",
        "total_found": len(reports),
        "new": new_count,
        "skipped": skipped_count,
        "errors": error_count,
        "new_settlement_ids": new_ids,
    }
    _emit(progress_id, f"Done. new={new_count} skipped={skipped_count} errors={error_count}")
    _set(progress_id, result)
    return result


# ─── Scheduler entry point ────────────────────────────────────────────────────

def sync_settlement_daily():
    """Daily scheduler job — check for new settlement reports."""
    frappe.logger().info("[settlement_daily] Checking for new settlement reports")
    try:
        return sync_settlement_reports(job_id=None)
    except Exception as e:
        err = str(e)
        frappe.log_error(err, "Amazon US Settlement Daily")
        return {"status": "error", "message": err}


# ─── Reconciliation helper ────────────────────────────────────────────────────

def get_settlement_reconciliation(settlement_id):
    """
    Cross-check a settlement's order lines against posted AR Invoices.
    Returns list of {order_id, settlement_principal, sap_doc_entry, match_status}.
    """
    if not frappe.db.exists(_SETTLEMENT_DOCTYPE, settlement_id):
        return {"status": "error", "message": "Settlement not found"}

    # Get all order-level principal amounts from settlement lines.
    # V2 format: amount_type='ItemPrice', amount_description='Principal'
    order_amounts = frappe.db.sql(
        """
        SELECT order_id, SUM(amount) AS settlement_amount
        FROM `tabAmazon US Settlement Line`
        WHERE parent = %s
          AND transaction_type = 'Order'
          AND amount_description = 'Principal'
          AND order_id != ''
        GROUP BY order_id
        """,
        settlement_id,
        as_dict=True,
    )

    rows = []
    for row in order_amounts:
        order_id = row.order_id
        sap_info = frappe.db.get_value(
            "Amazon US Order",
            order_id,
            ["sap_doc_entry", "sap_doc_num", "stage", "order_total_amount"],
            as_dict=True,
        ) or {}

        match_status = "unmatched"
        if sap_info.get("stage") == "posted":
            match_status = "posted"
        elif sap_info.get("stage") == "failed":
            match_status = "failed"
        elif sap_info.get("stage") in ("ready", "fetched"):
            match_status = "pending_post"

        rows.append({
            "order_id": order_id,
            "settlement_principal": row.settlement_amount,
            "order_total": sap_info.get("order_total_amount"),
            "sap_doc_entry": sap_info.get("sap_doc_entry"),
            "sap_doc_num": sap_info.get("sap_doc_num"),
            "match_status": match_status,
        })

    posted = sum(1 for r in rows if r["match_status"] == "posted")
    pending = sum(1 for r in rows if r["match_status"] == "pending_post")
    unmatched = sum(1 for r in rows if r["match_status"] == "unmatched")

    return {
        "status": "ok",
        "settlement_id": settlement_id,
        "order_lines": rows,
        "summary": {"posted": posted, "pending_post": pending, "unmatched": unmatched},
    }
